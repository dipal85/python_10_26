#19. Write a program to print the day name based on day number (1–7).

d = int(input("Day (1-7): "))
if d == 1: print("Monday")
elif d == 2: 
    print("Tuesday")
elif d == 3: 
    print("Wednesday")
elif d == 4: 
    print("Thursday")
elif d == 5: 
    print("Friday")
elif d == 6: 
    print("Saturday")
elif d == 7: 
    print("Sunday")
else: 
    print("Invalid Day Number")